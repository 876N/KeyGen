pub const RCON: [u8; 11] = [0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36];

fn gmul(mut a: u8, mut b: u8) -> u8 {
    let mut p: u8 = 0;
    for _ in 0..8 {
        if b & 1 != 0 {
            p ^= a;
        }
        let hi = (a & 0x80) != 0;
        a = a.wrapping_shl(1);
        if hi {
            a ^= 0x1b;
        }
        b >>= 1;
    }
    p
}

pub fn key_expand_256(key: &[u8; 32]) -> [u8; 240] {
    let mut rk = [0u8; 240];
    rk[..32].copy_from_slice(key);
    for i in 8..60 {
        let mut t = [0u8; 4];
        t.copy_from_slice(&rk[(i - 1) * 4..(i - 1) * 4 + 4]);
        if i % 8 == 0 {
            let tmp = t[0];
            t[0] = SBOX[t[1] as usize] ^ RCON[i / 8];
            t[1] = SBOX[t[2] as usize];
            t[2] = SBOX[t[3] as usize];
            t[3] = SBOX[tmp as usize];
        } else if i % 8 == 4 {
            t[0] = SBOX[t[0] as usize];
            t[1] = SBOX[t[1] as usize];
            t[2] = SBOX[t[2] as usize];
            t[3] = SBOX[t[3] as usize];
        }
        for j in 0..4 {
            rk[i * 4 + j] = rk[(i - 8) * 4 + j] ^ t[j];
        }
    }
    rk
}

pub fn enc_block(s: &mut [u8; 16], rk: &[u8; 240]) {
    for i in 0..16 {
        s[i] ^= rk[i];
    }
    for round in 1..14 {
        for i in 0..16 {
            s[i] = SBOX[s[i] as usize];
        }
        let t = s[1];
        s[1] = s[5];
        s[5] = s[9];
        s[9] = s[13];
        s[13] = t;
        let t = s[2];
        s[2] = s[10];
        s[10] = t;
        let t = s[6];
        s[6] = s[14];
        s[14] = t;
        let t = s[15];
        s[15] = s[11];
        s[11] = s[7];
        s[7] = s[3];
        s[3] = t;
        for c in 0..4 {
            let mut a = [0u8; 4];
            let mut b = [0u8; 4];
            for j in 0..4 {
                a[j] = s[c * 4 + j];
                b[j] = if s[c * 4 + j] & 0x80 != 0 {
                    (s[c * 4 + j].wrapping_shl(1)) ^ 0x1b
                } else {
                    s[c * 4 + j].wrapping_shl(1)
                };
            }
            s[c * 4 + 0] = b[0] ^ a[3] ^ a[2] ^ b[1] ^ a[1];
            s[c * 4 + 1] = b[1] ^ a[0] ^ a[3] ^ b[2] ^ a[2];
            s[c * 4 + 2] = b[2] ^ a[1] ^ a[0] ^ b[3] ^ a[3];
            s[c * 4 + 3] = b[3] ^ a[2] ^ a[1] ^ b[0] ^ a[0];
        }
        for i in 0..16 {
            s[i] ^= rk[round * 16 + i];
        }
    }
    for i in 0..16 {
        s[i] = SBOX[s[i] as usize];
    }
    let t = s[1];
    s[1] = s[5];
    s[5] = s[9];
    s[9] = s[13];
    s[13] = t;
    let t = s[2];
    s[2] = s[10];
    s[10] = t;
    let t = s[6];
    s[6] = s[14];
    s[14] = t;
    let t = s[15];
    s[15] = s[11];
    s[11] = s[7];
    s[7] = s[3];
    s[3] = t;
    for i in 0..16 {
        s[i] ^= rk[224 + i];
    }
}

pub fn dec_block(s: &mut [u8; 16], rk: &[u8; 240]) {
    for i in 0..16 {
        s[i] ^= rk[224 + i];
    }
    for round in (1..14).rev() {
        let t = s[13];
        s[13] = s[9];
        s[9] = s[5];
        s[5] = s[1];
        s[1] = t;
        let t = s[2];
        s[2] = s[10];
        s[10] = t;
        let t = s[6];
        s[6] = s[14];
        s[14] = t;
        let t = s[3];
        s[3] = s[7];
        s[7] = s[11];
        s[11] = s[15];
        s[15] = t;
        for i in 0..16 {
            s[i] = INV_SBOX[s[i] as usize];
        }
        for i in 0..16 {
            s[i] ^= rk[round * 16 + i];
        }
        for c in 0..4 {
            let mut a = [0u8; 4];
            for j in 0..4 {
                a[j] = s[c * 4 + j];
            }
            s[c * 4 + 0] = gmul(a[0], 0x0e) ^ gmul(a[1], 0x0b) ^ gmul(a[2], 0x0d) ^ gmul(a[3], 0x09);
            s[c * 4 + 1] = gmul(a[0], 0x09) ^ gmul(a[1], 0x0e) ^ gmul(a[2], 0x0b) ^ gmul(a[3], 0x0d);
            s[c * 4 + 2] = gmul(a[0], 0x0d) ^ gmul(a[1], 0x09) ^ gmul(a[2], 0x0e) ^ gmul(a[3], 0x0b);
            s[c * 4 + 3] = gmul(a[0], 0x0b) ^ gmul(a[1], 0x0d) ^ gmul(a[2], 0x09) ^ gmul(a[3], 0x0e);
        }
    }
    let t = s[13];
    s[13] = s[9];
    s[9] = s[5];
    s[5] = s[1];
    s[1] = t;
    let t = s[2];
    s[2] = s[10];
    s[10] = t;
    let t = s[6];
    s[6] = s[14];
    s[14] = t;
    let t = s[3];
    s[3] = s[7];
    s[7] = s[11];
    s[11] = s[15];
    s[15] = t;
    for i in 0..16 {
        s[i] = INV_SBOX[s[i] as usize];
    }
    for i in 0..16 {
        s[i] ^= rk[i];
    }
}

pub fn aes256_cbc_encrypt(data: &[u8], key: &[u8]) -> Vec<u8> {
    if key.len() != 32 {
        return Vec::new();
    }
    let mut k = [0u8; 32];
    k.copy_from_slice(&key[..32]);
    let rk = key_expand_256(&k);

    let mut iv = [0u8; 16];
    secure_random(&mut iv);

    let pad_len = ((data.len() / 16) + 1) * 16;
    let mut padded = vec![0u8; pad_len];
    padded[..data.len()].copy_from_slice(data);
    let pad_val = (pad_len - data.len()) as u8;
    for i in data.len()..pad_len {
        padded[i] = pad_val;
    }

    let mut out = Vec::with_capacity(16 + pad_len);
    out.extend_from_slice(&iv);
    let mut prev = iv;

    let mut i = 0;
    while i < pad_len {
        let mut block = [0u8; 16];
        for j in 0..16 {
            block[j] = padded[i + j] ^ prev[j];
        }
        enc_block(&mut block, &rk);
        out.extend_from_slice(&block);
        prev = block;
        i += 16;
    }
    out
}

pub fn aes256_cbc_decrypt(data: &[u8], key: &[u8]) -> Vec<u8> {
    if key.len() != 32 || data.len() < 32 {
        return Vec::new();
    }
    let mut k = [0u8; 32];
    k.copy_from_slice(&key[..32]);
    let rk = key_expand_256(&k);

    let mut prev = [0u8; 16];
    prev.copy_from_slice(&data[..16]);

    let mut out = Vec::with_capacity(data.len() - 16);
    let mut i = 16usize;
    while i + 16 <= data.len() {
        let mut block = [0u8; 16];
        block.copy_from_slice(&data[i..i + 16]);
        let enc_save = block;
        dec_block(&mut block, &rk);
        for j in 0..16 {
            out.push(block[j] ^ prev[j]);
        }
        prev = enc_save;
        i += 16;
    }

    if let Some(&pad) = out.last() {
        if pad > 0 && pad <= 16 && (pad as usize) <= out.len() {
            let start = out.len() - pad as usize;
            let ok = out[start..].iter().all(|&b| b == pad);
            if ok {
                out.truncate(start);
            }
        }
    }
    out
}
